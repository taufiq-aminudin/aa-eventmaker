export const getEventTypeById = (
  typeId: string,
  categories: EventCategoryDefinition[] = INITIAL_EVENT_CATEGORIES
): { eventType: EventTypeDefinition; category: EventCategoryDefinition } | null => {
  for (const cat of categories) {
    const found = cat.eventTypes.find((t) => t.id === typeId || t.name.toLowerCase() === typeId.toLowerCase());
    if (found) return { eventType: found, category: cat };
  }
  return null;
};
